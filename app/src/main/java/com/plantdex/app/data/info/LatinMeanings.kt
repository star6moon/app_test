/**
 * 학명(라틴어·그리스어)에 자주 나오는 속명·종소명의 뜻. '학명 뜻풀이' 에 씁니다.
 * 종소명은 어미가 바뀌어도(-us/-a/-um, -is/-e) 같은 뜻으로 찾습니다.
