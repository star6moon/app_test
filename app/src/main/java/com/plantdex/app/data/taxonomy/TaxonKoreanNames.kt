/**
 * 분류 단계(계·문·강·목·과)의 한국어 이름.
 * 자주 나오는 이름은 앱에 넣어 두고, 없으면 GBIF·Wikidata 에서 찾고([TaxonomyRepository]),
 * 그래도 없으면 학명 발음에 '목'·'과'·'속' 을 붙입니다.
 */
object TaxonKoreanNames {

    /** 앱에 넣어 둔 이름 (없으면 null) */
    fun known(scientificName: String): String? = NAMES[scientificName.trim()]

    /** 처음 보는 사람을 위한 짧은 설명 (예: 목련강 → 쌍떡잎식물) */
    fun hint(scientificName: String): String? = HINTS[scientificName.trim()]

    /** 한국어 이름 끝에 단계 이름(목·과·속)이 없으면 붙입니다. (예: 민들레 → 민들레속) */
    fun withSuffix(rank: TaxonRank, name: String): String {
        val trimmed = name.substringBefore(" (").trim()
        val suffix = SUFFIX[rank] ?: return trimmed
        return if (trimmed.endsWith(suffix)) trimmed else trimmed + suffix
    }

    /** 한국어 이름을 못 찾았을 때 학명 발음 (예: Picramniales → 피크람니아목). 계·문·강은 null. */
    fun pronunciation(rank: TaxonRank, scientificName: String): String? {
        val stem = when (rank) {
            TaxonRank.Order -> scientificName.removeSuffix("ales").plus("a").takeIf { scientificName.endsWith("ales") }
            TaxonRank.Family -> scientificName.removeSuffix("aceae").takeIf { scientificName.endsWith("aceae") }
                ?.let { if (it.last() in "aeiou") it else it + "a" }
            TaxonRank.Genus -> scientificName
            else -> null
        } ?: return null
        val sound = LatinHangul.transliterate(stem).takeIf { it.isNotBlank() } ?: return null
        return withSuffix(rank, sound)
    }

