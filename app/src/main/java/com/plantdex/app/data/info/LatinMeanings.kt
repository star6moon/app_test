    /** 학명의 속명·종소명 중 뜻을 아는 단어들 (모르면 빈 목록) */
    fun explain(scientificName: String): List<NameMeaning> {
        val words = scientificName.replace("×", " ").split(Regex("\\s+")).filter { it.isNotBlank() && it != "x" }
        val genus = words.firstOrNull() ?: return emptyList()
        val epithets = words.drop(1).takeWhile { it.first().isLowerCase() && it.all { c -> c.isLetter() || c == '-' } }.take(2)
        return buildList {
            GENERA[genus.lowercase()]?.let { add(NameMeaning(genus, it)) }
            for (e in epithets) epithet(e)?.let { add(NameMeaning(e, it)) }
        }
    }

    private fun epithet(word: String): String? {
        val w = word.lowercase()
        EPITHETS[w]?.let { return it }
        // 어미를 떼고 다시 찾기 (grandiflorum → grandiflor, japonica → japonic …)
        val stem = STEM_SUFFIXES.firstOrNull { w.endsWith(it) }?.let { w.removeSuffix(it) } ?: return null
        return EPITHET_STEMS[stem]
    }

